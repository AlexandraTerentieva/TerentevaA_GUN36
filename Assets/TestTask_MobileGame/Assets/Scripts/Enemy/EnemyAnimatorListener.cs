using System.Collections;
using System.Collections.Generic;
using UnityEngine;

/// <summary>
/// Слушатель анимаций для врага.
/// Вызывается из анимационных событий.
/// Создан отдельно для врага (по ТЗ).
/// </summary>
public class EnemyAnimatorListener : MonoBehaviour
{
    // ============================================================
    //  ПРИВАТНЫЕ ПЕРЕМЕННЫЕ
    // ============================================================

    private EnemyEntity entity;  // Ссылка на EnemyEntity (здоровье врага)

    // ============================================================
    //  СТАРТ
    //  Вызывается при запуске
    // ============================================================

    void Start()
    {
        // Получаем компонент EnemyEntity
        entity = GetComponent<EnemyEntity>();

        if (entity == null)
        {
            Debug.LogWarning($"⚠️ {name}: EnemyEntity не найден!");
        }
    }

    // ============================================================
    //  МЕТОДЫ, ВЫЗЫВАЕМЫЕ ИЗ АНИМАЦИЙ
    //  Эти методы вызываются через Animation Events
    // ============================================================

    /// <summary>
    /// Вызывается из анимации в момент удара
    /// </summary>
    public void OnHit()
    {
        Debug.Log($"💢 {name}: Анимация — УДАР!");
        // Здесь можно добавить эффекты удара
    }

    /// <summary>
    /// Вызывается из анимации в момент атаки
    /// </summary>
    public void OnAttack()
    {
        Debug.Log($"⚔️ {name}: Анимация — АТАКА!");

        // Если атака идёт через анимацию, здесь можно найти врагов и нанести урон
        // Но у нас атака вызывается из EnemyBehaviour, так что этот метод пока не используется
    }

    /// <summary>
    /// Вызывается из анимации в момент смерти
    /// </summary>
    public void OnDeath()
    {
        Debug.Log($"💀 {name}: Анимация — СМЕРТЬ!");

        // Дополнительные эффекты смерти (партиклы, звук и т.д.)
        // Можно добавить взрыв, искры и т.п.
    }

    /// <summary>
    /// Вызывается в конце анимации смерти
    /// </summary>
    public void OnDeathEnd()
    {
        Debug.Log($"✅ {name}: Анимация смерти завершена!");

        // Можно удалить объект или запустить дополнительные эффекты
        // Но у нас объект удаляется через Destroy в EnemyEntity.Die()
    }
}